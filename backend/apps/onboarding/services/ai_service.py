class GeminiAIService(BaseAIService):
    """
    Google Gemini LLM Provider.
    Invoked when GEMINI_API_KEY environment variable is configured.
    """
    PROVIDER_NAME = "Google Gemini Industrial Advisor"
    PROVIDER_KEY = "GEMINI_API"

    def __init__(self, api_key: str):
        self.api_key = api_key

    def generate_recommendations(self, prompt: str) -> dict:
        # If API fails or library unavailable, safely fall back to Smart Heuristic with explicit label
        try:
            import urllib.request
            url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={self.api_key}"
            system_instruction = (
                "You are an expert industrial automation and manufacturing systems architect. "
                "The user provides a description of their factory. Generate a JSON response with: "
                "factory (name, code, industry_type, industry_custom, capabilities), products (name, sku, unit_of_measure, target_hourly_rate), "
                "raw_materials (name, code, category, unit_of_measure, safety_stock), "
                "process_stages (sequence, name, cycle_time_seconds, quality_check_required, description), "
                "production_lines (name, code, target_hourly_units, machines [name, code, machine_type, rated_power_kw]), "
                "shifts (name, start_time, end_time, operating_days, planned_capacity_units), "
                "target_kpis (target_oee, target_availability, target_performance, target_quality, target_daily_capacity). "
                "Return valid JSON only."
            )
            payload = {
                "contents": [
                    {"role": "user", "parts": [{"text": f"{system_instruction}\n\nFactory Description:\n{prompt}"}]}
                ],
                "generationConfig": {"temperature": 0.2, "responseMimeType": "application/json"}
            }
            req = urllib.request.Request(
                url,
                data=json.dumps(payload).encode("utf-8"),
                headers={"Content-Type": "application/json"}
            )
            with urllib.request.urlopen(req, timeout=12) as res:
                body = json.loads(res.read().decode("utf-8"))
                text = body["candidates"][0]["content"]["parts"][0]["text"]
                parsed = json.loads(text)
                return {
                    "source": self.PROVIDER_KEY,
                    "provider_name": self.PROVIDER_NAME,
                    "disclaimer": "Generated via Google Gemini API. User confirmation required before applying.",
                    "confirmation_required": True,
                    "original_prompt": prompt,
                    "recommended_configuration": parsed,
                }
        except Exception as e:
            logger.warning("Gemini AI API call failed or timed out: %s. Falling back to Rule-based Heuristic.", e)
            fallback = RuleBasedSmartHeuristicAIService().generate_recommendations(prompt)
            fallback["disclaimer"] += f" (Note: Gemini API invocation encountered: {str(e)[:60]}...)"
            return fallback

def get_ai_service() -> BaseAIService:
    """
    Factory selector returning appropriate AI service based on environment variables.
    """
    gemini_key = os.getenv("GEMINI_API_KEY", "").strip()
    openai_key = os.getenv("OPENAI_API_KEY", "").strip()

    if gemini_key:
        return GeminiAIService(api_key=gemini_key)
    
    # Default to Rule-based heuristic mode
    return RuleBasedSmartHeuristicAIService()
